import { expect, test } from '@playwright/test';
import { adminPassword, expectAccessible, settle, signIn } from './helpers';

test('administrator drains and disables an edge before confirming removal', async ({ page }, info) => {
    await signIn(page, 'admin', 'admin@browser.test', adminPassword);
    const name = `retire-edge-${info.project.name}`;
    await page.goto('/admin/edges/create');
    await page.getByRole('textbox', { name: /^Name/ }).fill(name);
    await page.getByRole('button', { name: /^Country/ }).click();
    await page.getByRole('combobox', { name: /Country.*Search/ }).fill('DE');
    await page.getByRole('option', { name: 'DE', exact: true }).click();
    await page.getByLabel('Continent').selectOption('EU');
    await page.getByRole('button', { name: 'Create', exact: true }).click();
    await page.waitForURL(/\/admin\/edges\/[\w-]+$/);
    const enrollment = page.getByRole('dialog').filter({ hasText: 'Enroll this edge' });
    await enrollment.getByRole('checkbox').check();
    await enrollment.getByRole('button', { name: 'Finish enrollment setup', exact: true }).click();
    await expect(page.getByTestId('edge-remove')).toHaveCount(0);
    await page.goto('/admin/edges');
    const row = page.getByRole('row').filter({ hasText: name });
    await row.getByRole('button', { name: 'More', exact: true }).click();
    await page.getByRole('menuitem', { name: 'Disable', exact: true }).click();
    await page.getByRole('alertdialog').getByRole('button', { name: 'Confirm', exact: true }).click();
    await row.getByRole('button', { name: 'More', exact: true }).click();
    await expect(page.getByTestId('edge-remove')).toBeDisabled();
    await page.getByRole('menuitem', { name: 'Drain', exact: true }).click();
    await page.getByRole('alertdialog').getByRole('button', { name: 'Confirm', exact: true }).click();
    await row.getByRole('link').first().click();
    await settle(page);
    await page.getByTestId('edge-remove').focus();
    await page.keyboard.press('Enter');
    const dialog = page.locator('.fi-modal-window:visible').filter({ hasText: 'Remove edge' });
    await expect(dialog).toBeVisible();
    await expectAccessible(page);
    await expect(dialog).toHaveScreenshot('edge-remove-confirmation.png');
    await dialog.getByTestId('edge-remove-cancel').click();
    await expect(page.getByTestId('edge-remove')).toBeVisible();
    await page.getByTestId('edge-remove').click();
    await dialog.getByTestId('edge-remove-confirm').click();
    await page.waitForURL('/admin/edges');
    await expect(page.getByRole('row').filter({ hasText: name })).toHaveCount(0);
});
