"""Host firewall for internal listeners.

Docker publishes container ports straight through the host's forwarding path, so a
host firewall such as ufw does not see them. This module renders `firewall.sh`, which
puts a default-deny chain in front of every internal listener (exporters, DNSdist
statistics, the PowerDNS transfer port) and admits only the fleet's own addresses.
Public listeners (DNS, HTTP, HTTPS, edge control) are never touched.
"""
from __future__ import annotations

import ipaddress
from typing import Any

# Internal listeners and the roles that publish them. Ports are published by Docker (forwarded path)
# unless listed in HOST_NETWORK_PORTS, which belong to a host-network service.
FORWARDED_PORTS: dict[str, tuple[tuple[int, str], ...]] = {
    "node_exporter": ((9100, "tcp"),),
    "dnsdist_statistics": ((8083, "tcp"),),
    "vector_metrics": ((9598, "tcp"), (9599, "tcp")),
    "powerdns_transfer": ((5300, "tcp"), (5300, "udp")),
}
HOST_NETWORK_PORTS: dict[str, tuple[tuple[int, str], ...]] = {
    "edge_gateway_metrics": ((9105, "tcp"),),
}
ADDRESS_FIELDS = ("public_ipv4", "public_ipv6", "bind_ipv4", "bind_ipv6", "monitor_ipv4", "monitor_ipv6", "log_ipv4", "log_ipv6")
WILDCARDS = {"0.0.0.0", "::"}


def fleet_addresses(state: dict[str, Any]) -> tuple[list[str], list[str]]:
    """Addresses of every enabled node, split by IP family. Wildcard bind addresses are not sources."""
    v4: set[str] = set()
    v6: set[str] = set()
    for node in state["nodes"].values():
        if not node.get("enabled"):
            continue
        for field in ADDRESS_FIELDS:
            value = node.get(field)
            if not value or value in WILDCARDS:
                continue
            (v4 if ipaddress.ip_address(value).version == 4 else v6).add(value)
    return sorted(v4, key=ipaddress.ip_address), sorted(v6, key=ipaddress.ip_address)


def render_firewall_script(state: dict[str, Any], node: dict[str, Any]) -> str:
    """An idempotent root script that applies the default-deny rules for this node and reapplies them after a reboot."""
    v4, v6 = fleet_addresses(state)
    forwarded = [f"{port}/{proto}" for ports in FORWARDED_PORTS.values() for port, proto in ports]
    host = [f"{port}/{proto}" for ports in HOST_NETWORK_PORTS.values() for port, proto in ports]
    return f"""#!/usr/bin/env sh
# Generated by the Fleet tool for node {node['name']}. Do not edit; rerun start.sh after changing the fleet.
set -eu
if [ "$(id -u)" != "0" ]; then
    echo "firewall.sh must run as root." >&2
    exit 1
fi
FLEET_V4="{' '.join(v4)}"
FLEET_V6="{' '.join(v6)}"
FORWARDED_PORTS="{' '.join(forwarded)}"
HOST_PORTS="{' '.join(host)}"

apply_family() {{
    ipt="$1"; fleet="$2"
    command -v "$ipt" >/dev/null 2>&1 || return 0
    "$ipt" -w -L DOCKER-USER >/dev/null 2>&1 || "$ipt" -w -N DOCKER-USER 2>/dev/null || return 0
    for chain in CDNF-INTERNAL-FORWARD CDNF-INTERNAL-INPUT; do
        "$ipt" -w -N "$chain" 2>/dev/null || "$ipt" -w -F "$chain"
    done
    # Traffic between containers on this host arrives on a Docker bridge and is not judged here.
    "$ipt" -w -A CDNF-INTERNAL-FORWARD -i docker0 -j RETURN
    "$ipt" -w -A CDNF-INTERNAL-FORWARD -i 'br-+' -j RETURN
    # Forwarded (Docker-published) ports: judge the connection's original destination port.
    for entry in $FORWARDED_PORTS; do
        port="${{entry%/*}}"; proto="${{entry#*/}}"
        for source in $fleet; do
            "$ipt" -w -A CDNF-INTERNAL-FORWARD -p "$proto" -m conntrack --ctorigdstport "$port" --ctdir ORIGINAL -s "$source" -j RETURN
        done
        "$ipt" -w -A CDNF-INTERNAL-FORWARD -p "$proto" -m conntrack --ctorigdstport "$port" --ctdir ORIGINAL -j DROP
    done
    "$ipt" -w -A CDNF-INTERNAL-FORWARD -j RETURN
    # Host-network services: loopback, container bridges, and the fleet only.
    "$ipt" -w -A CDNF-INTERNAL-INPUT -i lo -j RETURN
    "$ipt" -w -A CDNF-INTERNAL-INPUT -i docker0 -j RETURN
    "$ipt" -w -A CDNF-INTERNAL-INPUT -i 'br-+' -j RETURN
    for entry in $HOST_PORTS; do
        port="${{entry%/*}}"; proto="${{entry#*/}}"
        for source in $fleet; do
            "$ipt" -w -A CDNF-INTERNAL-INPUT -p "$proto" --dport "$port" -s "$source" -j RETURN
        done
        "$ipt" -w -A CDNF-INTERNAL-INPUT -p "$proto" --dport "$port" -j DROP
    done
    "$ipt" -w -A CDNF-INTERNAL-INPUT -j RETURN
    "$ipt" -w -C DOCKER-USER -j CDNF-INTERNAL-FORWARD 2>/dev/null || "$ipt" -w -I DOCKER-USER 1 -j CDNF-INTERNAL-FORWARD
    "$ipt" -w -C INPUT -j CDNF-INTERNAL-INPUT 2>/dev/null || "$ipt" -w -I INPUT 1 -j CDNF-INTERNAL-INPUT
}}

apply_family iptables "$FLEET_V4"
apply_family ip6tables "$FLEET_V6"

# Docker's own chains are rebuilt on boot, so the rules are applied again before containers return.
if [ -d /run/systemd/system ] && [ "${{1:-}}" != "--no-boot-unit" ]; then
    here="$(cd "$(dirname "$0")" && pwd)"
    cat > /etc/systemd/system/cdnfoundry-firewall.service <<UNIT
[Unit]
Description=CDNFoundry internal listener firewall
After=docker.service network-online.target
Wants=docker.service

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=$here/firewall.sh --no-boot-unit

[Install]
WantedBy=multi-user.target
UNIT
    systemctl daemon-reload
    systemctl enable cdnfoundry-firewall.service >/dev/null 2>&1 || true
fi
echo "Internal listener firewall applied for {node['name']}."
"""
