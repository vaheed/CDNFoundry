#!/usr/bin/env python3
"""Write docker/prometheus/slo-rules.yml: recording rules and multi-window burn-rate alerts for every SLO.

Each SLO is a bad-event ratio over a window. The burn rate is that ratio divided by the error budget
(1 - objective). A fast burn pages when both the 1h and 5m windows burn the budget 14.4 times too fast; a
slow burn opens a ticket when both the 6h and 30m windows burn it 6 times too fast. Run with --check in CI.
"""
from __future__ import annotations

import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "docker/prometheus/slo-rules.yml"
WINDOWS = ("5m", "30m", "1h", "6h")

# name -> (title, objective, team, dashboard uid, runbook anchor, bad-ratio expression with {w} for the window)
SLOS = {
    "edge_availability": (
        "Edge availability", 0.999, "noc", "cdnf-noc-wall", "edge-availability-burn",
        '1 - avg(avg_over_time(probe_success{{job="blackbox-http"}}[{w}]))',
    ),
    "edge_5xx": (
        "Edge 5xx ratio", 0.999, "noc", "cdnf-global-traffic", "edge-5xx-burn",
        'sum(rate(cdnf_edge_requests_total{{status_class="5xx"}}[{w}])) / sum(rate(cdnf_edge_requests_total[{w}]))',
    ),
    "edge_latency": (
        "Edge latency (95 percent under 500 ms)", 0.95, "noc", "cdnf-edge-latency", "edge-latency-burn",
        '1 - sum(rate(cdnf_edge_request_duration_seconds_bucket{{le="0.5"}}[{w}])) / sum(rate(cdnf_edge_request_duration_seconds_count[{w}]))',
    ),
    "purge_propagation": (
        "Purge propagation (applied within 30 s)", 0.99, "platform", "cdnf-propagation", "propagation-burn",
        "avg_over_time((cdnfoundry_purge_pending_oldest_seconds > bool 30)[{w}:1m])",
    ),
    "config_propagation": (
        "Config propagation (applied within 120 s)", 0.99, "platform", "cdnf-propagation", "propagation-burn",
        "avg_over_time((cdnfoundry_config_pending_oldest_seconds > bool 120)[{w}:1m])",
    ),
    "dns_answer": (
        "DNS answer success", 0.999, "noc", "cdnf-dns-authoritative", "dns-answer-burn",
        'sum(rate(cdnf_dns_queries_total{{rcode="SERVFAIL"}}[{w}])) / sum(rate(cdnf_dns_queries_total[{w}]))',
    ),
    "telemetry_delivery": (
        "Telemetry delivery", 0.999, "platform", "cdnf-telemetry-pipeline", "telemetry-delivery-burn",
        'sum(rate(vector_component_discarded_events_total{{component_id=~"clickhouse_.*"}}[{w}])) / (sum(rate(vector_component_sent_events_total{{component_id=~"clickhouse_.*"}}[{w}])) + sum(rate(vector_component_discarded_events_total{{component_id=~"clickhouse_.*"}}[{w}])))',
    ),
}


def build() -> dict:
    recordings = []
    alerts = []
    for name, (title, objective, team, dashboard, anchor, expression) in SLOS.items():
        budget = round(1 - objective, 6)
        for window in WINDOWS:
            recordings.append({"record": f"slo:{name}:bad_ratio_rate{window}", "expr": expression.format(w=window)})
        recordings.append({"record": f"slo:{name}:objective", "expr": f"vector({objective})"})
        recordings.append({"record": f"slo:{name}:error_budget", "expr": f"vector({budget})"})
        recordings.append({"record": f"slo:{name}:bad_ratio_30d", "expr": f"avg_over_time(slo:{name}:bad_ratio_rate1h[30d])"})
        recordings.append({
            "record": f"slo:{name}:budget_remaining",
            "expr": f"1 - clamp_max(slo:{name}:bad_ratio_30d / {budget}, 1)",
        })
        for speed, long, short, factor, severity in (("Fast", "1h", "5m", 14.4, "critical"), ("Slow", "6h", "30m", 6, "warning")):
            alerts.append({
                "alert": f"SLOBurn{''.join(part[:1].upper() + part[1:] for part in name.split('_'))}{speed}",
                "expr": f"slo:{name}:bad_ratio_rate{long} > {factor} * {budget} and slo:{name}:bad_ratio_rate{short} > {factor} * {budget}",
                "for": "2m" if speed == "Fast" else "15m",
                "labels": {"team": team, "severity": severity, "slo": name, "dashboard": "cdnf-slos"},
                "annotations": {
                    "summary": f"{title} is burning its error budget {factor} times too fast over {long} and {short}",
                    "runbook_url": f"https://vaheed.github.io/CDNFoundry/operations/runbooks#{anchor}",
                    "dashboard_url": f"/d/cdnf-slos?var-slo={name}",
                },
            })
    return {"groups": [
        {"name": "cdnfoundry-slo-recordings", "interval": "1m", "rules": recordings},
        {"name": "cdnfoundry-slo-burn-rate", "rules": alerts},
    ]}


def render() -> str:
    header = "# Generated by scripts/observability/build_slo_rules.py. Edit the script, then run it.\n"
    return header + yaml.safe_dump(build(), sort_keys=False, width=200)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        if OUTPUT.read_text() != text:
            sys.exit("docker/prometheus/slo-rules.yml is out of date; run scripts/observability/build_slo_rules.py")
    else:
        OUTPUT.write_text(text)
