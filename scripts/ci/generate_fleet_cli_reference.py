#!/usr/bin/env python3
"""Generate docs/reference/fleet-cli.md from the Fleet command definitions.

Run without arguments to write the page, or with --check to fail when it is out of date.
"""
import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))

from cdnfoundry_fleet.cli import parser  # noqa: E402

TARGET = ROOT / "docs/reference/fleet-cli.md"
HEADER = """---
title: Fleet CLI reference
description: Every cdnfoundry-fleet command and option, generated from the command definitions.
---

# Fleet CLI reference

<!-- Generated by scripts/ci/generate_fleet_cli_reference.py. Do not edit by hand. -->

This page is generated from the `cdnfoundry-fleet` command definitions, so it always
matches the tool. For a task-oriented walk-through, see the
[Fleet operator guide](../deployment/production-fleet-operator-guide.md).

Run `scripts/cdnfoundry-fleet <command> --help` for the same text in a terminal.
"""


def clean(text: str | None) -> str:
    """Collapse whitespace and put <placeholders> in code spans so they are not read as HTML."""
    return re.sub(r"<([^<>\s]+)>", r"`<\1>`", " ".join((text or "").split()))


def visible_actions(command: argparse.ArgumentParser) -> list[argparse.Action]:
    return [  # argparse has no public accessor for a command's options
        action
        for action in command._actions
        if not isinstance(action, (argparse._HelpAction, argparse._SubParsersAction))
        and action.option_strings
        and action.help != argparse.SUPPRESS
    ]


def options(command: argparse.ArgumentParser) -> list[str]:
    rows: list[str] = []
    for action in visible_actions(command):
        flags = ", ".join(f"`{flag}`" for flag in action.option_strings)
        value = "" if action.nargs == 0 else f" `{(action.metavar or action.dest).upper()}`"
        extra = []
        if action.choices:
            extra.append("one of " + ", ".join(f"`{c}`" for c in action.choices))
        if action.required:
            extra.append("required")
        detail = clean(action.help).replace(" (default: %(default)s)", "")
        if extra:
            detail = f"{detail} ({'; '.join(extra)})".strip()
        rows.append(f"| {flags}{value} | {detail or 'No description.'} |")
    return rows


def subcommands(command: argparse.ArgumentParser) -> argparse._SubParsersAction | None:
    return next((a for a in command._actions if isinstance(a, argparse._SubParsersAction)), None)


def section(lines: list[str], name: str, command: argparse.ArgumentParser, summary: str, shared: set[str], level: int) -> None:
    lines += [f"{'#' * level} {name}", ""]
    summary = summary or clean(command.description)
    if summary:
        lines += [summary[0].upper() + summary[1:] + ("" if summary.endswith(".") else "."), ""]
    specific = [
        row for row, action in zip(options(command), visible_actions(command)) if not set(action.option_strings) & shared
    ]
    lines += ["| Option | Meaning |", "| --- | --- |", *specific, ""] if specific else ["No options beyond the shared ones.", ""]
    nested = subcommands(command)
    if nested is not None:
        helps = {choice.dest: clean(choice.help) for choice in nested._choices_actions}
        for child in sorted(nested.choices):
            section(lines, f"{name} {child}", nested.choices[child], helps.get(child, ""), shared, level + 1)


def render() -> str:
    root = parser()
    sub = subcommands(root)
    help_by_name = {choice.dest: clean(choice.help) for choice in sub._choices_actions}
    shared_actions = visible_actions(root)
    shared = {flag for action in shared_actions for flag in action.option_strings}
    lines = [HEADER]
    if shared_actions:
        lines += ["## Options for every command", "", "| Option | Meaning |", "| --- | --- |", *options(root), ""]
    for name in sorted(sub.choices):
        section(lines, name, sub.choices[name], help_by_name.get(name, ""), shared, 2)
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    content = render()
    if "--check" in sys.argv:
        if not TARGET.is_file() or TARGET.read_text(encoding="utf-8") != content:
            print("docs/reference/fleet-cli.md is out of date; run scripts/ci/generate_fleet_cli_reference.py")
            return 1
        print("fleet_cli_reference=passed")
        return 0
    TARGET.write_text(content, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
