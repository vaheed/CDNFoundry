#!/usr/bin/env python3
"""Generate docs/reference/grafana-dashboards.md from the provisioned Grafana dashboards.

Run without arguments to write the page, or with --check to fail when it is out of date.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
GRAFANA = ROOT / "docker/grafana"
TARGET = ROOT / "docs/reference/grafana-dashboards.md"

FOLDERS = {
    "00-overview": ("Overview", "everyone"),
    "10-noc": ("NOC", "`noc`"),
    "20-soc": ("SOC", "`soc`"),
    "30-platform-admin": ("Platform admin", "`platform-admin`"),
    "40-on-call-slo": ("On-call and SLO", "`noc` and `soc`"),
    "50-domains": ("Domains", "`support`"),
    "60-business-capacity": ("Business and capacity", "`business`"),
    "90-samples": ("Samples", "everyone"),
}

HEADER = """---
title: Grafana dashboards reference
description: Every provisioned Grafana dashboard, who sees it, how often it refreshes, and what each panel shows. Generated from the dashboard files.
---

# Grafana dashboards reference

<!-- Generated by scripts/ci/generate_grafana_reference.py. Do not edit by hand. -->

This page lists every dashboard that CDNFoundry provisions into Grafana, with
what each panel shows. It is generated from the dashboard files, so it matches
what you see. For how to sign in and which team sees which folder, read the
[Grafana guide](../operations/grafana.md).
"""


def library_panels() -> dict[str, dict]:
    panels = {}
    for path in (GRAFANA / "library-panels").glob("*.json"):
        data = json.loads(path.read_text(encoding="utf-8"))
        panels[data["uid"]] = data["model"]
    return panels


def cell(text: str | None) -> str:
    return " ".join((text or "").replace("|", "\\|").split()) or "No description."


def render() -> str:
    library = library_panels()
    lines = [HEADER]
    for folder, (label, team) in FOLDERS.items():
        files = sorted((GRAFANA / "dashboards" / folder).glob("*.json"))
        if not files:
            continue
        lines += [f"## {label}", "", f"Seen by {team}.", ""]
        for path in files:
            dashboard = json.loads(path.read_text(encoding="utf-8"))
            lines += [f"### {dashboard['title']}", ""]
            lines += [cell(dashboard.get("description")), ""]
            lines += [f"Refreshes every {dashboard.get('refresh') or 'never (manual)'}.", ""]
            rows = []
            for panel in dashboard.get("panels", []):
                if panel.get("type") in {"row", "text"}:
                    continue
                shown = library.get(panel.get("libraryPanel", {}).get("uid"), {}) if "libraryPanel" in panel else {}
                title = panel.get("title") or shown.get("title") or ""
                description = panel.get("description") or shown.get("description")
                if title:
                    rows.append(f"| {cell(title)} | {cell(description)} |")
            if rows:
                lines += ["| Panel | What it shows |", "| --- | --- |", *rows, ""]
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    content = render()
    if "--check" in sys.argv:
        if not TARGET.is_file() or TARGET.read_text(encoding="utf-8") != content:
            print("docs/reference/grafana-dashboards.md is out of date; run scripts/ci/generate_grafana_reference.py")
            return 1
        print("grafana_reference=passed")
        return 0
    TARGET.write_text(content, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
