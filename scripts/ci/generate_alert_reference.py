#!/usr/bin/env python3
"""Generate docs/reference/alerts.md from the Prometheus alert rules.

Run without arguments to write the page, or with --check to fail when it is out of date.
"""
import json
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[2]
RULES = ROOT / "docker/prometheus"
TARGET = ROOT / "docs/reference/alerts.md"
GRAFANA = ROOT / "docker/grafana/dashboards"
RUNBOOK_PREFIX = "https://vaheed.github.io/CDNFoundry/operations/runbooks"

HEADER = """---
title: Alert reference
description: Every alert CDNFoundry can raise, who gets it, how long the problem must last, and the runbook and dashboard that explain it. Generated from the alert rules.
---

# Alert reference

<!-- Generated by scripts/ci/generate_alert_reference.py. Do not edit by hand. -->

Look up an alert by its name. Each row gives the team it goes to, its severity,
how long the problem must last before it fires, what it means, and where to go
next. This page is generated from the alert rules, so it lists exactly the alerts
that exist.

- **Team** says who gets the alert: `platform`, `noc`, or `soc`.
- **Fires after** is how long the condition must hold. "Immediately" means as soon
  as it is true.
- **Runbook** has the symptoms, the checks, and the fix.
- **Dashboard** is the Grafana dashboard that shows the cause. See
  [Grafana by team](../operations/grafana-by-team.md).
"""


def runbook_link(url: str) -> str:
    anchor = url.removeprefix(RUNBOOK_PREFIX)
    return f"[Runbook](../operations/runbooks.md{anchor})" if anchor.startswith("#") or not anchor else ""


def dashboard_titles() -> dict[str, str]:
    titles = {}
    for path in GRAFANA.rglob("*.json"):
        data = json.loads(path.read_text(encoding="utf-8"))
        titles[data["uid"]] = data["title"]
    return titles


def alerts() -> list[dict]:
    found = []
    for path in sorted(RULES.glob("*.yml")):
        document = yaml.safe_load(path.read_text(encoding="utf-8"))
        if not isinstance(document, dict):
            continue
        for group in document.get("groups", []):
            for rule in group.get("rules", []):
                if "alert" in rule:
                    found.append(rule)
    return found


def render() -> str:
    by_team: dict[str, list[dict]] = {}
    for rule in alerts():
        by_team.setdefault(rule["labels"]["team"], []).append(rule)
    titles = dashboard_titles()
    severity_order = {"critical": 0, "warning": 1, "info": 2}
    lines = [HEADER, f"There are {sum(len(v) for v in by_team.values())} alerts.", ""]
    for team in sorted(by_team):
        lines += [f"## Team: {team}", "", "| Alert | Severity | Fires after | What it means | Runbook | Dashboard |", "| --- | --- | --- | --- | --- | --- |"]
        for rule in sorted(by_team[team], key=lambda r: (severity_order.get(r["labels"]["severity"], 9), r["alert"])):
            annotations = rule["annotations"]
            dashboard = rule["labels"].get("dashboard", "")
            lines.append(
                f"| `{rule['alert']}` | {rule['labels']['severity']} | {rule.get('for') or 'Immediately'} "
                f"| {' '.join(str(annotations.get('summary', '')).split()).replace('|', chr(92) + '|')} "
                f"| {runbook_link(annotations.get('runbook_url', ''))} | {titles.get(dashboard, dashboard)} |"
            )
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    content = render()
    if "--check" in sys.argv:
        if not TARGET.is_file() or TARGET.read_text(encoding="utf-8") != content:
            print("docs/reference/alerts.md is out of date; run scripts/ci/generate_alert_reference.py")
            return 1
        print("alert_reference=passed")
        return 0
    TARGET.write_text(content, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
